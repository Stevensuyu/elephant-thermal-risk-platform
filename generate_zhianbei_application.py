METHODS = """项目研究的基本思路、具体研究方法或算法、研究计划及可行性等。

一、基本思路。
本项目遵循“问题场景牵引—指标体系构建—数据流程设计—平台原型实现—模拟情景验证—迭代优化完善”的研究思路。首先，从边境象群活动监测和低空安全风险治理场景出发，明确平台需要解决的实际问题：夜间或复杂环境下象群目标发现不及时、风险判断依赖人工经验、预警信息缺少统一分级、巡护处置缺少可视化辅助。其次，围绕无人机热成像和边缘 AI 的技术特点，设计可落地的数据链路：热成像图像或视频由无人机采集，边缘端完成目标检测和参数提取，平台端完成综合风险计算，Web 端完成地图展示和预警表达。再次，在无真实大规模数据的初期阶段，采用模拟数据与专家规则进行原型验证，先验证系统逻辑闭环和功能可用性，后续再逐步接入实地数据进行模型训练和校正。

二、总体架构设计。
平台拟采用“五层架构”。第一层为数据采集层，主要包括无人机热成像设备、模拟热成像图像流、地理基础数据、敏感区域数据和历史事件数据。第二层为边缘推理层，主要完成热目标检测、目标框定位、目标数量估计、目标置信度输出和关键帧上传。第三层为风险计算层，负责对目标特征、空间距离、时间条件、历史风险和处置条件进行综合评分，输出风险等级。第四层为数据服务层，负责存储目标记录、风险事件、预警日志、巡护处置记录和设备状态。第五层为 Web 应用层，面向管理人员和巡护人员提供实时地图、风险热区、预警弹窗、事件列表、历史回放、设备状态和处置建议。

三、数据流程设计。
平台数据流程分为六个环节。第一，采集环节：无人机热成像设备采集图像或视频流，模拟阶段可使用预设图像、视频片段或结构化模拟数据替代真实视频输入。第二，边缘推理环节：边缘端部署轻量化目标检测模型或模拟推理模块，输出目标类别、目标框坐标、置信度、目标数量、时间戳和设备编号。第三，地理映射环节：结合无人机 GPS、飞行高度、云台角度和地图坐标，将识别目标映射到地理位置；在模拟阶段可直接使用预设经纬度坐标。第四，风险计算环节：平台根据目标特征和周边环境参数计算综合风险分值。第五，预警生成环节：系统根据风险分值和规则阈值生成不同等级的预警事件。第六，展示与处置环节：Web 平台将预警以地图颜色、弹窗、列表和处置建议形式展示，并记录人工确认、误报标注和处置反馈。

四、多风险评估指标体系。
指标体系拟分为六类。第一类为目标风险指标，包括象群数量、目标聚集度、是否存在幼象、移动速度、移动方向、目标识别置信度。第二类为空间接近指标，包括距村寨距离、距农田距离、距道路距离、距学校或人员密集区距离、距边境线距离、距保护地边界距离。第三类为时间敏感指标，包括夜间时段、清晨/傍晚高活动时段、节假日或人员活动高峰时段。第四类为环境诱因指标，包括水源距离、坡度、植被覆盖、土地利用类型、天气条件和可视性。第五类为历史风险指标，包括历史出没频次、历史冲突点密度、近期预警次数。第六类为处置能力指标，包括巡护人员距离、道路通达性、通信状态、无人机电量和边缘设备在线状态。

五、风险评分模型。
综合风险分值 R 可采用加权评分与规则触发相结合的方法表示：
R = w1T + w2S + w3M + w4E + w5H + w6C。
其中，T 表示目标风险，S 表示空间接近风险，M 表示时间敏感风险，E 表示环境诱因风险，H 表示历史风险，C 表示处置能力风险；w1 至 w6 为权重。初期权重可采用专家赋权法设定，例如目标风险 0.20、空间接近风险 0.30、时间敏感风险 0.15、环境诱因风险 0.10、历史风险 0.15、处置能力风险 0.10。后续如获得真实数据，可使用层次分析法、熵权法、随机森林特征重要性或逻辑回归系数对权重进行校正。

风险等级可划分为四级：0—25 分为低风险，表示象群距离敏感区域较远或无明显接近趋势；26—50 分为中风险，表示象群活动需要持续关注；51—75 分为高风险，表示象群接近村寨、农田、道路等敏感区域，需要提醒巡护人员关注；76—100 分为极高风险，表示象群数量较多、距离敏感区域较近、夜间活动或移动方向指向高敏区域，需要立即发布预警并建议巡护处置。除综合分值外，平台还应设置强制触发规则，如“距村寨小于 500 米且夜间活动”“象群向人员密集区移动且距离持续缩短”“边缘设备识别到多目标聚集且历史风险区域重合”等情形可直接提升预警等级。

六、边缘 AI 方案。
在原型阶段，边缘 AI 模块可采用两种实现路径。第一种为模拟推理路径，即预设目标检测结果，重点验证数据接口、风险计算和平台展示。第二种为轻量模型路径，即使用 YOLO 系列轻量模型、MobileNet-SSD 或其他适合边缘端部署的目标检测模型，对热成像图像进行目标框检测。由于当前缺乏真实亚洲象热成像训练集，本项目不承诺完成高精度识别模型训练，而是将边缘 AI 模块设计为可替换接口，支持后续导入真实训练模型。边缘端输出字段包括 device_id、timestamp、target_type、bbox、confidence、target_count、latitude、longitude、speed、direction 和 frame_url 等。

七、Web 平台功能设计。
平台拟设置七个功能模块。第一，实时监测地图模块，展示无人机位置、识别目标位置、风险等级和敏感区域边界。第二，风险预警模块，根据风险等级显示不同颜色和预警弹窗。第三，事件管理模块，记录预警时间、地点、风险原因、处置状态和处置结果。第四，历史轨迹模块，支持查看象群模拟移动轨迹和风险变化趋势。第五，指标配置模块，允许调整指标权重、阈值和规则。第六，设备状态模块，展示无人机电量、边缘设备在线状态、通信状态和最近上传时间。第七，巡护建议模块，根据风险原因自动生成建议，如“加强村寨周边巡查”“提醒农田区域人员避让”“保持无人机持续跟踪但避免低空惊扰”等。

八、研究方法。
本项目采用文献研究法、需求分析法、系统设计法、指标体系构建法、规则建模法、原型开发法和模拟验证法。文献研究法用于梳理无人机热成像、边缘 AI、人象冲突风险评估和预警平台相关研究；需求分析法用于提炼边境巡护中的实际功能需求；系统设计法用于构建平台架构和数据流程；指标体系构建法用于形成多风险等级评价框架；规则建模法用于建立可解释的风险评分与分级规则；原型开发法用于实现 Web 平台基本功能；模拟验证法用于构建不同情景，检验系统从数据输入到风险输出的闭环。

九、模拟验证方案。
模拟验证设置四类情景。情景一为低风险情景：单个或少量热目标远离村寨、农田和道路，系统应输出低风险或中风险。情景二为接近风险情景：象群距离村寨或农田逐渐缩短，系统应显示风险等级上升趋势。情景三为夜间高风险情景：夜间多目标聚集并向敏感区域移动，系统应触发高风险或极高风险预警。情景四为设备异常情景：边缘设备离线、无人机电量不足或通信中断，系统应生成设备状态提醒，避免将监测盲区误判为安全状态。验证指标包括数据流程完整性、风险等级输出一致性、预警触发准确性、界面展示清晰度和处置记录完整性。

十、研究计划。
第一阶段为准备阶段，时间为第 1—2 周，完成文献收集、申报书完善、需求分析和技术路线确定。第二阶段为模型设计阶段，时间为第 3—5 周，完成指标体系、风险评分规则和数据字段设计。第三阶段为原型开发阶段，时间为第 6—10 周，完成 Web 平台页面、模拟数据接口、风险计算模块和预警展示模块。第四阶段为模拟验证阶段，时间为第 11—13 周，构建典型情景数据，测试平台功能和风险分级逻辑。第五阶段为总结完善阶段，时间为第 14—16 周，完成研究报告、项目展示材料、系统说明书和后续实地应用方案。

十一、可行性分析。
技术上，本项目不依赖立即获取真实大规模数据，而是先通过模拟数据和规则模型实现系统闭环，难度适中，符合学生科研创新项目特点。方法上，多风险评估指标可以从既有人象冲突研究、巡护实践和专家意见中提炼，具有可解释性。平台开发上，Web 可视化、地图展示、事件列表和规则计算均可通过常见前端框架与后端接口实现。应用上，项目对低空安全风险治理、边境生态保护、基层预警处置和人象冲突防范具有现实意义。风险控制上，项目明确不开展未经许可的边境飞行、不采集敏感地理数据、不宣称未经验证的预测效果，保证研究边界清晰、材料表述稳健。

十二、核心数据字段设计。
为保证平台后续可扩展，项目拟设计统一数据字段。无人机设备表包括设备编号、设备名称、所属区域、在线状态、电量、经纬度、飞行高度、最近通信时间。目标识别表包括事件编号、设备编号、时间戳、目标类型、目标数量、目标框坐标、置信度、经纬度、速度、方向和图像帧地址。风险评估表包括目标风险分、空间风险分、时间风险分、环境风险分、历史风险分、处置能力风险分、综合分值、风险等级和触发原因。预警事件表包括预警编号、预警等级、预警位置、预警时间、处置状态、处置人员、处置建议、人工确认结果和备注。通过结构化字段设计，可实现从“识别结果”到“风险事件”的数据转换，也便于后续开展统计分析和模型优化。

十三、平台原型页面与交互设计。
平台首页拟采用监测态势大屏形式，左侧显示设备列表、事件统计和风险等级分布，中间显示地图与实时目标点位，右侧显示最新预警、风险原因和处置建议。地图上使用绿色、黄色、橙色、红色分别表示低、中、高、极高风险。点击预警点后，可查看目标数量、识别置信度、距离敏感区域、触发规则、历史事件和建议处置方式。平台还应设置“指标配置”页面，允许研究人员调整权重和阈值；设置“模拟情景”页面，用于生成不同象群位置、数量、方向和时段的数据；设置“事件复盘”页面，用于查看某一次预警从识别到处置的完整过程。交互设计坚持简洁清晰，避免过度堆叠图表，重点让巡护人员能快速判断风险等级、风险原因和下一步行动。

十四、安全、伦理与合规边界。
项目涉及无人机、边境、野生动物和预警数据，应在申报材料中明确合规边界。第一，项目阶段不开展未经许可的边境实飞，不采集敏感地理信息，不公开具体边境坐标和巡护路线。第二，平台展示数据采用模拟坐标或脱敏区域，避免泄露敏感空间信息。第三，无人机应用应遵守低空飞行管理要求，避免低空近距离追逐或惊扰象群。第四，AI 输出只作为辅助预警信息，不替代专业人员判断。第五，后续如接入真实数据，应建立数据授权、访问控制、日志记录和脱敏处理机制。通过上述设计，项目能够在展示技术创新的同时，兼顾生态保护、公共安全和科研诚信要求。

十五、团队分工建议。
项目团队不超过 5 人时，可按模块分工。项目负责人负责总体方案、申报书统筹、技术路线和汇报展示；成员一负责文献综述、指标体系和风险规则设计；成员二负责前端页面、地图展示和交互原型；成员三负责后端接口、模拟数据和风险计算模块；成员四负责测试验证、演示视频、PPT 和材料整理。指导教师负责研究方向把关、材料规范审阅和比赛答辩指导。该分工既覆盖研究、建模、开发和展示，又符合学生科研项目团队协作特点。"""

